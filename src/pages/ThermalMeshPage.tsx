  const calculateQuantumPhysics = useCallback((params: QuantumDriveParams, velocity: number): QuantumPerformance => {
    if (!systemComponents.quantumDrive) {
        return { quantumThrust: 0, quantumDrag: 0, quantumPowerConsumption: 0, quantumHeatGeneration: 0 };
    }

    const { electronDensityTarget, magneticFieldStrength, magneticFieldAsymmetry, laserIntensity, electronCoherence, crystalIntegrity } = params;

    // Thrust Model: Depends on density, asymmetric field, coherence, integrity (PDF: electron control, asymmetric fields)
    const thrust = K_THRUST * electronDensityTarget * (magneticFieldStrength * magneticFieldAsymmetry) * electronCoherence * crystalIntegrity;

    // Drag Model: Base drag reduced by coherence/integrity (PDF: reduced interaction/drag)
    const dragReduction = electronCoherence * crystalIntegrity * K_DRAG_REDUCTION_FACTOR;
    const effectiveDragCoeff = K_DRAG_BASE * (1 - dragReduction);
    const drag = effectiveDragCoeff * Math.pow(velocity, 2);

    // Power Consumption Model: Base + density + field^2 + laser (PDF: control efforts)
    const powerConsumption = K_POWER_BASE + 
                             K_POWER_DENSITY * electronDensityTarget + 
                             K_POWER_FIELD * Math.pow(magneticFieldStrength, 2) + 
                             K_POWER_LASER * laserIntensity;

    // Heat Generation Model: Based on inefficiency, scaled by control intensity
    const efficiency = QUANTUM_DRIVE_EFFICIENCY_BASE * electronCoherence * crystalIntegrity;
    const inefficiencyFactor = (1 + laserIntensity + magneticFieldAsymmetry) / 2; // Average intensity factor
    const heatGeneration = powerConsumption * (1 - efficiency) * inefficiencyFactor * K_HEAT_FACTOR;

    return {
      quantumThrust: thrust,
      quantumDrag: drag,
      quantumPowerConsumption: powerConsumption,
      quantumHeatGeneration: heatGeneration
    };
  }, [systemComponents.quantumDrive]); // Dependency added

