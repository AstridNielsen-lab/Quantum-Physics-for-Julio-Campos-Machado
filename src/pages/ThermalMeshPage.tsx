  const updateQuantumState = useCallback((params: QuantumDriveParams, performance: QuantumPerformance): Partial<QuantumDriveParams> => {
    let { electronCoherence, crystalIntegrity } = params;
    const { quantumThrust, quantumHeatGeneration } = performance;

    // Coherence degrades with laser and field intensity, recovers slowly (PDF: control affects state)
    const coherenceDegradation = (params.laserIntensity * K_COHERENCE_DEGRADE_LASER + 
                                 (params.magneticFieldStrength * params.magneticFieldAsymmetry) * K_COHERENCE_DEGRADE_FIELD) * TIME_STEP;
    electronCoherence -= coherenceDegradation;
    electronCoherence += K_COHERENCE_RECOVERY * (1 - electronCoherence) * TIME_STEP; // Recover towards 1
    electronCoherence = Math.max(0, Math.min(1, electronCoherence));

    // Integrity degrades with thrust stress and heat stress (PDF: material stability)
    crystalIntegrity -= Math.abs(quantumThrust) * K_INTEGRITY_DEGRADE_THRUST * TIME_STEP;
    crystalIntegrity -= quantumHeatGeneration * K_INTEGRITY_DEGRADE_HEAT * TIME_STEP;
    crystalIntegrity = Math.max(0, Math.min(1, crystalIntegrity));

    return { electronCoherence, crystalIntegrity };
  }, []); // Constants are stable, no external dependencies needed


